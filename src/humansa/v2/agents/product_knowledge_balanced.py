def parse_balanced_products():
    """Parse balanced format into structured data"""
    products = []
    current_category = ""
    
    lines = NOAH_PRODUCTS_BALANCED.strip().split('\n')
    current_product = None
    
    for line in lines:
        line = line.strip()
        if not line:
            if current_product:
                products.append(current_product)
                current_product = None
            continue
        
        # Category header
        if line.startswith('═══【') and line.endswith('═══'):
            current_category = line.replace('═══【', '').replace('】', '').split('】')[0]
            current_product = None
        
        # Product number and name
        elif line and line[0].isdigit() and '.' in line:
            if current_product:
                products.append(current_product)
            
            parts = line.split('.', 1)
            if len(parts) == 2:
                current_product = {
                    'category': current_category,
                    'name': parts[1].strip(),
                    'tags': [],
                    'efficacy': '',
                    'usage': '',
                    'ingredients': '',
                    'contraindications': ''
                }
        
        # Product attributes
        elif current_product and ':' in line:
            key, value = line.split(':', 1)
            key = key.strip()
            value = value.strip()
            
            if key == '标签':
                current_product['tags'] = [t.strip() for t in value.split(',')]
            elif key == '功效':
                current_product['efficacy'] = value
            elif key == '用法':
                current_product['usage'] = value
            elif key in ['成分', '含量', '规格']:
                current_product['ingredients'] = value
            elif key in ['禁忌', '适用', '特点']:
                current_product['contraindications'] = value
    
    # Don't forget the last product
    if current_product:
        products.append(current_product)
    
    return products

class BalancedProductKnowledge:
    """Balanced product knowledge provider"""
    
    @staticmethod
    def get_knowledge_for_prompt():
        """Get product knowledge formatted for prompt injection"""
        return NOAH_PRODUCTS_BALANCED
    
    @staticmethod
    def search_products(query: str, limit: int = 10):
        """Search in balanced format with better matching"""
        query_lower = query.lower()
        results = []
        products = parse_balanced_products()
        
        for product in products:
            score = 0
            
            # Name matching
            if query_lower in product['name'].lower():
                score += 10
            
            # Tag matching
            for tag in product.get('tags', []):
                if query_lower in tag.lower():
                    score += 8
                if tag.lower() in query_lower:
                    score += 5
            
            # Efficacy matching
            if query_lower in product.get('efficacy', '').lower():
                score += 6
            
            # Category matching
            if query_lower in product.get('category', '').lower():
                score += 3
            
            if score > 0:
                results.append({
                    **product,
                    'score': score
                })
        
        # Sort by score
        results.sort(key=lambda x: x['score'], reverse=True)
        return results[:limit]
    
    @staticmethod
    def get_token_estimate():
        """Estimate tokens for balanced format"""
        text = NOAH_PRODUCTS_BALANCED
        # More accurate estimation
        # Chinese characters ≈ 2 tokens each
        # English/numbers ≈ 0.25 tokens each
        chinese_chars = sum(1 for c in text if '\u4e00' <= c <= '\u9fff')
        other_chars = len(text) - chinese_chars
        
        estimated_tokens = (chinese_chars * 2) + (other_chars * 0.25)
        return int(estimated_tokens)