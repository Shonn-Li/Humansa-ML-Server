def get_minimal_product_knowledge():
    """Get minimal product knowledge for prompt injection"""
    return NOAH_PRODUCTS_MINIMAL

def parse_minimal_products():
    """Parse minimal format into structured data"""
    categories = {}
    current_category = None
    
    lines = NOAH_PRODUCTS_MINIMAL.strip().split('\n')
    
    for line in lines:
        line = line.strip()
        if not line:
            continue
            
        if line.startswith('[') and line.endswith(']'):
            # Category line: [Category Name + Count]
            cat_info = line[1:-1]
            # Extract name and count
            if any(char.isdigit() for char in cat_info):
                # Find where the number starts
                for i in range(len(cat_info)-1, -1, -1):
                    if not cat_info[i].isdigit():
                        break
                current_category = cat_info[:i+1]
                categories[current_category] = []
        elif ':' in line and '|' in line and current_category:
            # Product line: Name:Tags|Description
            parts = line.split(':', 1)
            if len(parts) == 2:
                name = parts[0].strip()
                rest = parts[1]
                if '|' in rest:
                    tags_part, desc = rest.split('|', 1)
                    tags = [t.strip() for t in tags_part.split(',')]
                    
                    product = {
                        'name': name,
                        'tags': tags,
                        'description': desc.strip()
                    }
                    categories[current_category].append(product)
    
    return categories

# Example usage in agent
class MinimalProductKnowledge:
    """Minimal product knowledge provider"""
    
    @staticmethod
    def get_knowledge_for_prompt():
        """Get product knowledge formatted for prompt injection"""
        return NOAH_PRODUCTS_MINIMAL
    
    @staticmethod
    def search_products(query: str):
        """Simple search in minimal format"""
        query_lower = query.lower()
        results = []
        
        categories = parse_minimal_products()
        
        for cat_name, products in categories.items():
            for product in products:
                score = 0
                
                # Check name
                if query_lower in product['name'].lower():
                    score += 10
                
                # Check tags
                for tag in product['tags']:
                    if query_lower in tag.lower():
                        score += 5
                    if tag.lower() in query_lower:
                        score += 3
                
                # Check description
                if query_lower in product['description'].lower():
                    score += 2
                
                if score > 0:
                    results.append({
                        'category': cat_name,
                        'name': product['name'],
                        'tags': product['tags'],
                        'description': product['description'],
                        'score': score
                    })
        
        # Sort by score
        results.sort(key=lambda x: x['score'], reverse=True)
        return results[:10]